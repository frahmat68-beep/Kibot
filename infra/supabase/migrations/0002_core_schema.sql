create table if not exists public.daily_trade_summary (
    bot_id text not null references public.bots(bot_id) on delete cascade,
    summary_date date not null,
    trade_count integer not null default 0,
    win_count integer not null default 0,
    loss_count integer not null default 0,
    gross_volume_idr numeric(38, 18) not null default 0,
    realized_pnl_idr numeric(38, 18) not null default 0,
    created_at timestamptz not null default timezone('utc', now()),
    updated_at timestamptz not null default timezone('utc', now()),
    primary key (bot_id, summary_date)
);

create index if not exists idx_devices_user on public.devices(user_id);
create index if not exists idx_heartbeats_bot_observed on public.engine_heartbeats(bot_id, observed_at desc);
create index if not exists idx_commands_bot_created on public.command_queue(bot_id, created_at desc);
create index if not exists idx_execution_actions_bot_expires on public.execution_actions(bot_id, expires_at);
create index if not exists idx_orders_bot_updated on public.orders(bot_id, updated_at desc);
create index if not exists idx_orders_bot_status on public.orders(bot_id, status);
create index if not exists idx_fills_bot_executed on public.fills(bot_id, executed_at desc);
create index if not exists idx_positions_bot_state on public.positions(bot_id, state);
create index if not exists idx_logs_bot_created on public.logs(bot_id, created_at desc);
create index if not exists idx_market_snapshots_bot_pair_captured on public.market_snapshots(bot_id, pair_id, captured_at desc);
create index if not exists idx_strategy_metrics_bot_pair_created on public.strategy_metrics(bot_id, pair_id, created_at desc);


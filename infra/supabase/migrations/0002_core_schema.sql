    captured_at timestamptz not null
);

create table if not exists public.cleanup_runs (
    cleanup_run_id uuid primary key default gen_random_uuid(),
    bot_id text not null references public.bots(bot_id) on delete cascade,
    started_at timestamptz not null default timezone('utc', now()),
    finished_at timestamptz,
    status text not null check (status in ('RUNNING', 'SUCCEEDED', 'FAILED')),
    retention_days integer not null default 90,
    deleted_rows jsonb not null default '{}'::jsonb,
    error_message text

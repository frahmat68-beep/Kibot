    snapshot_id bigint generated by default as identity primary key,
    bot_id text not null references public.bots(bot_id) on delete cascade,
    pair_id text not null,
    best_bid numeric(38, 18) not null,
    best_ask numeric(38, 18) not null,
    mid_price numeric(38, 18) not null,
    spread_pct numeric(12, 6) not null,
    quote_volume_24h numeric(38, 18) not null,
    base_volume_24h numeric(38, 18) not null,
    estimated_slippage_pct numeric(12, 6) not null,
